// The exhaustion circuits' sources (succinct-read §4.3): three leaves over one carried state (transactions,
// transaction trees and headers, map updates), the node and the two folds. Each `main.nr` is generated here, the
// leaves from their slot counts and the scan's tables (src/ergo-scan.ts, so the circuit and the prover's map read
// transactions alike), the node and folds from the key hashes they hold. `exhaustion.nr`, `blake2b.nr` and the
// vendored sponge are shared. Imported by exhaustion-set.mjs and the checks; run after `npm run build`.
import { SCAN_ACTION_FIELDS, SCAN_ACTIONS, SCAN_BYTE, SCAN_GROUP, SCAN_KEY, SCAN_MODES } from "../../dist/ergo-scan.js";

export const HEADER = "// Generated by scripts/venue/exhaustion-sources.mjs; do not edit.\n";
/** Entries a transaction slot's list holds: an output with the shape spans at least 42 bytes. */
export const LIST_PER_SLOT = 4;
const PRELUDE = `mod poseidon2;
mod blake2b;
mod exhaustion;
// The vendored sponge calls crate::poseidon2_permutation.
use std::hash::poseidon2_permutation;
use exhaustion::{M, T, U};
`;
const table = (name, type, values) => `global ${name}: [${type}; ${values.length}] = [${values.join(", ")}];\n`;
const signed = x => (x < 0 ? `-${-x}` : `${x}`);

/** The scan's tables as the transaction leaf reads them. */
function scanTables() {
  if (SCAN_MODES[0] !== "V_IN") throw new Error("the scan's first mode is not V_IN");
  let s = table("GROUP", "u32", SCAN_GROUP) + table("BYTE", "Field", SCAN_BYTE) + table("KEY", "u32", SCAN_KEY);
  for (const f of SCAN_ACTION_FIELDS) s += table(`A_${f}`, f === "NEXT" ? "u32" : "Field", SCAN_ACTIONS.map(a => signed(a[f])));
  return s;
}

/** The transaction leaf: CT slots of at most 128 bytes, each one Blake2b compression and 128 scan steps, and a list of
 * the entries the scan emits, LIST_PER_SLOT a slot, checked against them as a multiset. */
export function leafT(CT) {
  const EL = LIST_PER_SLOT * CT;
  return `${HEADER}// The transaction leaf (succinct-read §4.3), ${CT} slots: it hashes each transaction's unsigned bytes in slots of
// at most 128 bytes, a transaction starting a fresh compression and its last slot zero past its length, scans them
// with src/ergo-scan.ts's machine from its start state at each transaction's first byte, joins each finished
// transaction's id with its labels (its block's height and its position) to the id chain, and lists the entries the
// scan emits (an output with venue-ergo §6's shape: subject, height, position, output), in order, each joining the
// entry stream. The list is checked against what the scan emits as multisets under two challenges hashed from the
// leaf's two state hashes, which bind every byte it hashed and the list. Public inputs (sin, sout, nodeKeyHash);
// nodeKeyHash is free here and bound by whoever admits the proof (§2 rule 1).
${PRELUDE}use exhaustion::{entry_chain, id_chain, index, is_zero, mask, P32, state_hash, T_EX_CHALLENGE};
use poseidon2::Poseidon2;

global CT: u32 = ${CT};
global EL: u32 = ${EL};
${scanTables()}
unconstrained fn split_byte(v: Field) -> (bool, u8) {
    let w = v as u32;
    ((w & 1) == 1, (w >> 1) as u8)
}

fn main(
    sin: pub Field, sout: pub Field, node_key_hash: pub Field, t0: T, m: M, u: U,
    tb: [[u8; 128]; CT], tlen: [Field; CT], tstart: [bool; CT], tnew: [bool; CT], tlast: [bool; CT],
    lu: [bool; EL], lhi: [Field; EL], llo: [Field; EL], lheight: [Field; EL], lposition: [Field; EL], loutput: [Field; EL],
) {
    let _ = node_key_hash;
    assert(state_hash(t0, m, u) == sin, "start state");
    let mut t = t0;
    let gamma = Poseidon2::hash([T_EX_CHALLENGE, sin, sout, 1], 4);
    let delta = Poseidon2::hash([T_EX_CHALLENGE, sin, sout, 2], 4);

    // The list, in strictly increasing (height, position, output), each joining the entry stream.
    let mut listed: Field = 1;
    let mut was_used = true;
    let mut last: Field = 0;
    for k in 0..EL {
        let used = lu[k] as Field;
        assert(used * (1 - was_used as Field) == 0, "list prefix");
        was_used = lu[k];
        let (hi, lo, height, position, output) = (lhi[k], llo[k], lheight[k], lposition[k], loutput[k]);
        hi.assert_max_bit_size::<128>();
        lo.assert_max_bit_size::<128>();
        height.assert_max_bit_size::<32>();
        position.assert_max_bit_size::<32>();
        output.assert_max_bit_size::<32>();
        let place = (height * P32 + position) * P32 + output;
        if k > 0 {
            (used * (place - last - 1)).assert_max_bit_size::<96>();
        }
        last = place;
        listed = listed * (1 + used * (gamma - (hi + delta * (lo + delta * place)) - 1));
        let next = entry_chain(t.echain, hi, lo, height, position, output);
        t.echain = t.echain + used * (next - t.echain);
    }

    let mut emitted: Field = 1;
    for s in 0..CT {
        let len = tlen[s];
        let used = 1 - is_zero(len);
        let act = mask(len);
        let st = tstart[s] as Field;
        let la = tlast[s] as Field;
        let nw = tnew[s] as Field;
        // A slot starts or ends a transaction only if used, starts a block only where it starts a transaction,
        // starts exactly where none is open, and is full unless it ends one.
        assert(st * (1 - used) == 0);
        assert(la * (1 - used) == 0);
        assert(nw * (1 - st) == 0, "block start");
        assert(st * (t.in_tx as Field) == 0, "start inside a transaction");
        assert((1 - st) * used * (1 - t.in_tx as Field) == 0, "slot outside a transaction");
        assert((1 - la) * used * (len - 128) == 0, "short slot");
        let b = tb[s];
        for j in 0..128 {
            assert(b[j] as Field * (1 - act[j]) == 0, "byte past a slot");
        }
        let h_in = if tstart[s] { blake2b::iv0() } else { t.h };
        let count = if tstart[s] { 0 } else { t.t };
        let counted = count + (index(len) as u64);
        let mut words = [0; 16];
        for i in 0..16 {
            words[i] = blake2b::word(b, i);
        }
        let d = blake2b::compress(h_in, words, counted, tlast[s]);
        if used == 1 {
            t.h = d;
            t.t = counted;
            t.in_tx = !tlast[s];
        }
        // A transaction starts: its labels advance and the scan starts from src/ergo-scan.ts's SCAN_START.
        t.height = t.height + nw;
        t.j = t.j + st - nw * (t.j + 1);
        if tstart[s] {
            t.mode = 0;
            t.r = 0;
            t.c1 = 0;
            t.c2 = 0;
            t.a = 0;
            t.p = 1;
            t.hi = 0;
            t.lo = 0;
            t.sh = 0;
            t.outi = 0;
        }
        let labels = (t.height * P32 + t.j) * P32;
        let mut mode = t.mode;
        let (mut r, mut c1, mut c2, mut a, mut p) = (t.r, t.c1, t.c2, t.a, t.p);
        let (mut hi, mut lo, mut sh, mut outi) = (t.hi, t.lo, t.sh, t.outi);
        for j in 0..128 {
            let byte = b[j];
            let bf = byte as Field;
            let v = BYTE[GROUP[mode] * 256 + (byte as u32)];
            // Safety: v = cont + 2 cls with cont a bit and cls a u8 has one solution.
            let (cont, cls) = unsafe { split_byte(v) };
            assert(v == (cont as Field) + 2 * (cls as Field));
            let value = a + (bf - 128 * (cont as Field)) * p;
            let z_r = is_zero(r - 1);
            let z_v = is_zero(value);
            let z_32 = is_zero(value - 32);
            let z_c1 = is_zero(c1 - 1);
            let z_c2 = is_zero(c2 - 1);
            let id = KEY[index((mode as Field) * 128 + (cls as Field) * 32 + z_r * 16 + z_v * 8 + z_32 * 4 + z_c1 * 2 + z_c2)];
            r = A_RK[id] * r + A_RC[id] + A_RV[id] * value;
            c1 = A_C1K[id] * c1 + A_C1C[id] + A_C1V[id] * value;
            c2 = A_C2K[id] * c2 + A_C2C[id] + A_C2B[id] * bf;
            let continues = A_VK[id];
            a = continues * value;
            p = continues * (128 * p - 1) + 1;
            hi = A_HM[id] * hi + A_HB[id] * bf;
            lo = A_LM[id] * lo + A_LB[id] * bf;
            sh = A_SHM[id] * sh + A_SHC[id];
            // An output ends at a byte of the transaction: with the shape, its entry joins the emitted multiset.
            let ends = A_OEND[id] * act[j];
            let emit = ends * is_zero(sh - 2);
            let entry = hi + delta * (lo + delta * (labels + outi));
            emitted = emitted + emit * emitted * (gamma - entry - 1);
            outi = outi + ends;
            mode = A_NEXT[id];
        }
        if used == 1 {
            t.mode = mode;
            t.r = r;
            t.c1 = c1;
            t.c2 = c2;
            t.a = a;
            t.p = p;
            t.hi = hi;
            t.lo = lo;
            t.sh = sh;
            t.outi = outi;
        }
        // A transaction ends: its id joins the chain with its labels.
        let next = id_chain(t.chain, [d[0], d[1], d[2], d[3]], t.height, t.j);
        t.chain = t.chain + la * (next - t.chain);
    }
    assert(state_hash(t, m, u) == sout, "end state");
    assert(emitted == listed, "list");
}
`;
}

/** The tree-and-header leaf: CM slots, each one Blake2b compression of a tree leaf (an id or a witness id), a tree
 * node (a merge or a lone child), or a header's chunk. */
export function leafM(CM) {
  return `${HEADER}// The tree-and-header leaf (succinct-read §4.3), ${CM} slots: venue-ergo §4's transactions-root trees and the
// headers, one Blake2b compression a slot, through a stack machine. An id or a witness id is pushed as a leaf hash, a
// merge hashes the two top entries as a node, a lift hashes the top alone as a lone child's node; a header's first
// chunk requires a single entry on the stack equal to its transactions root (bytes 65-97) and its parent id (bytes
// 1-33) equal to the last header's id. Each id pushed joins the id chain with its labels. Positions 0 and 1 of the
// stack are sentinels: a merge needs two live entries and a lift one, so the root depends on every id pushed. Public
// inputs (sin, sout, nodeKeyHash), nodeKeyHash free as in every leaf.
${PRELUDE}use exhaustion::{id_chain, index, is_zero, mask, spells, state_hash};

global CM: u32 = ${CM};

fn main(
    sin: pub Field, sout: pub Field, node_key_hash: pub Field, t: T, m0: M, u: U,
    mb: [[u8; 128]; CM], mlen: [Field; CM], mop: [[bool; 5]; CM], mlast: [bool; CM], mid: [[u64; 4]; CM],
) {
    let _ = node_key_hash;
    assert(state_hash(t, m0, u) == sin, "start state");
    let mut m = m0;
    for s in 0..CM {
        // At most one of: an id, a witness id, a merge, a lift, a header chunk.
        let o = mop[s];
        let (o_id, o_wid, o_mrg, o_lift, o_hdr) = (o[0] as Field, o[1] as Field, o[2] as Field, o[3] as Field, o[4] as Field);
        let any = o_id + o_wid + o_mrg + o_lift + o_hdr;
        assert(any * (1 - any) == 0);
        let tree = any - o_hdr;
        let ml = mlast[s] as Field;
        assert(ml * (1 - o_hdr) == 0);
        let len = mlen[s];
        let act = mask(len);
        assert(o_id * (len - 33) == 0);
        assert(o_wid * (len - 32) == 0);
        assert(o_mrg * (len - 65) == 0);
        assert(o_lift * (len - 33) == 0);
        assert(o_hdr * (1 - ml) * (len - 128) == 0);
        assert(o_hdr * is_zero(len) == 0);
        assert((1 - any) * len == 0);
        let b = mb[s];
        for j in 0..128 {
            assert((b[j] as Field) * (1 - act[j]) == 0, "byte past a slot");
        }
        assert((o_id + o_wid) * (b[0] as Field) == 0, "leaf prefix");
        assert((o_mrg + o_lift) * (b[0] as Field - 1) == 0, "node prefix");
        assert(tree * (m.in_hdr as Field) == 0, "tree inside a header");
        let sp = m.sp;
        let top = m.stack[sp + 1];
        let below = m.stack[sp];
        let first = o_hdr * (1 - m.in_hdr as Field);
        spells(o_id, b, 1, mid[s], "pushed id");
        spells(o_mrg, b, 1, below, "merged entries");
        spells(o_mrg, b, 33, top, "merged entries");
        spells(o_lift, b, 1, top, "lifted entry");
        spells(first, b, 1, m.prev, "parent id");
        spells(first, b, 65, top, "transactions root");
        assert(first * (sp as Field - 1) == 0, "one root");
        assert(o_mrg * is_zero(sp as Field - 1) == 0, "merge into a sentinel");
        assert(o_lift * is_zero(sp as Field) == 0, "lift over an empty stack");
        let continued = (o_hdr == 1) & m.in_hdr;
        let h_in = if continued { m.mh } else { blake2b::iv0() };
        let count = if continued { m.hc } else { 0 };
        let counted = count + (index(len) as u64);
        let last = (o_hdr == 0) | mlast[s];
        let mut words = [0; 16];
        for i in 0..16 {
            words[i] = blake2b::word(b, i);
        }
        let d = blake2b::compress(h_in, words, counted, last);
        // The stack.
        let push = o_id + o_wid;
        let at = index(sp as Field + 1 + push - o_mrg);
        let write = push + o_mrg + o_lift;
        let old = m.stack[at];
        let mut value = old;
        for k in 0..4 {
            value[k] = if write == 1 { d[k] } else { old[k] };
        }
        m.stack[at] = value;
        let next = id_chain(m.chain, mid[s], m.height + 1, m.j);
        m.chain = m.chain + o_id * (next - m.chain);
        m.j = m.j + o_id;
        // The header.
        if o_hdr == 1 {
            m.mh = d;
            m.hc = counted;
            m.in_hdr = !mlast[s];
        }
        let done = o_hdr * ml;
        if done == 1 {
            m.prev = [d[0], d[1], d[2], d[3]];
        }
        m.height = m.height + done;
        m.j = m.j * (1 - done);
        m.sp = index((sp as Field + push - o_mrg) * (1 - done));
    }
    assert(state_hash(t, m, u) == sout, "end state");
}
`;
}

/** The map-update leaf: E slots, each the entry stream's next entry appended to its key's chain in the map. */
export function leafU(E) {
  return `${HEADER}// The map-update leaf (succinct-read §4.3), ${E} slots: each used slot takes the entry stream's next entry
// (subject, height, position, output), appends it to its key's chain (the subject's last four bytes) and replaces the
// key's leaf in the map (§4.2), checking the old leaf against the root through its 32 siblings. Public inputs (sin,
// sout, nodeKeyHash), nodeKeyHash free as in every leaf.
${PRELUDE}use exhaustion::{D, entry_chain, is_zero, map_leaf, map_node, P32, state_hash};

global E: u32 = ${E};
unconstrained fn split_key(x: Field) -> (Field, Field) {
    let v = x as u128;
    ((v / 4294967296) as Field, (v % 4294967296) as Field)
}

fn main(
    sin: pub Field, sout: pub Field, node_key_hash: pub Field, t: T, m: M, u0: U,
    uu: [bool; E], uhi: [Field; E], ulo: [Field; E], uheight: [Field; E], uposition: [Field; E], uoutput: [Field; E],
    ucount: [Field; E], uchain: [Field; E], usiblings: [[Field; D]; E],
) {
    let _ = node_key_hash;
    assert(state_hash(t, m, u0) == sin, "start state");
    let mut u = u0;
    let mut was_used = true;
    for k in 0..E {
        let used = uu[k] as Field;
        assert(used * (1 - was_used as Field) == 0);
        was_used = uu[k];
        let (hi, lo, height, position, output) = (uhi[k], ulo[k], uheight[k], uposition[k], uoutput[k]);
        let next = entry_chain(u.chain, hi, lo, height, position, output);
        u.chain = u.chain + used * (next - u.chain);
        // The key: lo = q 2^32 + key, q below 2^96, so the key is lo's last 32 bits wherever lo is below 2^128 (the
        // transaction leaves range-check what joins the stream).
        // Safety: q and the key are range-checked and recompose lo.
        let (q, key) = unsafe { split_key(lo) };
        q.assert_max_bit_size::<96>();
        let bits: [bool; 32] = key.to_le_bits();
        assert(q * P32 + key == lo, "key");
        let (count, chain) = (ucount[k], uchain[k]);
        let empty = is_zero(count);
        assert(empty * chain == 0, "empty leaf");
        let old = (1 - empty) * map_leaf(count, chain);
        let new = map_leaf(count + 1, entry_chain(chain, hi, lo, height, position, output));
        let mut a = old;
        let mut b = new;
        for i in 0..D {
            let sibling = usiblings[k][i];
            let (al, ar) = if bits[i] { (sibling, a) } else { (a, sibling) };
            let (bl, br) = if bits[i] { (sibling, b) } else { (b, sibling) };
            a = map_node(al, ar);
            b = map_node(bl, br);
        }
        assert(used * (a - u.root) == 0, "map path");
        u.root = u.root + used * (b - u.root);
    }
    assert(state_hash(t, m, u) == sout, "end state");
}
`;
}

const list = values => values.map(v => `    ${v},`).join("\n");
/** The node: two children under the leaf keys (constants) or its own (nodeKeyHash), joined end to start. */
export function node({ t, m, u }) {
  return `${HEADER}// The exhaustion node (succinct-read §4.3): it verifies two children, each under a key whose hash is one of the
// three leaves' (constants here) or the node's own, the public input nodeKeyHash, with public inputs (start, end,
// nodeKeyHash), and requires the left child's end to be the right child's start. Its public inputs are (sin, sout,
// nodeKeyHash): the left's start, the right's end. The backend binds each child's key to the key hash it is
// verified under (bb 5.2.0's recursive verifier, as the trail node).
mod poseidon2;
mod exhaustion;
// The vendored sponge calls crate::poseidon2_permutation.
use std::hash::poseidon2_permutation;
use exhaustion::{HONK_ZK, KEY_FIELDS, PROOF_FIELDS};

// The leaves' key hashes: transactions, trees and headers, map updates.
global LEAF_KEY_HASHES: [Field; 3] = [
${list([t, m, u])}
];

fn main(
    sin: pub Field, sout: pub Field, node_key_hash: pub Field,
    keys: [[Field; KEY_FIELDS]; 2], proofs: [[Field; PROOF_FIELDS]; 2], key_hashes: [Field; 2], middle: Field,
) {
    let ends = [[sin, middle], [middle, sout]];
    for i in 0..2 {
        let mut admitted = key_hashes[i] == node_key_hash;
        for j in 0..3 {
            admitted = admitted | (key_hashes[i] == LEAF_KEY_HASHES[j]);
        }
        assert(admitted, "child key");
        std::verify_proof_with_type(keys[i], proofs[i], [ends[i][0], ends[i][1], node_key_hash], key_hashes[i], HONK_ZK);
    }
}
`;
}

const foldInputs = `    start_hi: pub Field, start_lo: pub Field, start_height: pub Field, end_hi: pub Field, end_lo: pub Field,
    end_height: pub Field, map_root: pub Field, fold_key_hash: pub Field,`;
const foldPeriod = `    // The period's tree: its root under a leaf key or the node's, carrying the node's key hash.
    let mut admitted = key_hash == NODE_KEY_HASH;
    for j in 0..3 {
        admitted = admitted | (key_hash == LEAF_KEY_HASHES[j]);
    }
    assert(admitted, "tree key");
    std::verify_proof_with_type(key, proof, [state_hash(t0, m0, u0), state_hash(t1, m1, u1), NODE_KEY_HASH], key_hash, HONK_ZK);
    assert_start(t0, m0, u0);
    assert_end(t1, m1, u1);
    let (hi, lo) = id_limbs(m1.prev);
    assert(end_hi == hi, "end id");
    assert(end_lo == lo, "end id");
    assert(end_height == m1.height, "end height");
    assert(map_root == u1.root, "map root");`;
const foldHeader = (what, { t, m, u, n }) => `${HEADER}${what}
mod poseidon2;
mod exhaustion;
// The vendored sponge calls crate::poseidon2_permutation.
use std::hash::poseidon2_permutation;
use exhaustion::{assert_end, assert_start, HONK_ZK, id_limbs, KEY_FIELDS, M, PROOF_FIELDS, state_hash, T, U};

// The leaves' key hashes (transactions, trees and headers, map updates) and the node's.
global LEAF_KEY_HASHES: [Field; 3] = [
${list([t, m, u])}
];
global NODE_KEY_HASH: Field = ${n};
`;
/** The first fold: a period from the start the reader pins, the map empty there. */
export function foldFirst(keys, emptyRoot) {
  return `${foldHeader(`// The first fold (succinct-read §4.3): it verifies a period's tree under the leaf keys or the node's key and
// requires the period to start at a period's start (§4.3's canonical state) with the map empty, at the start header
// its public inputs name, and to end at a block boundary where both pairs of chains are equal. Public inputs, in
// order: startHi, startLo, startHeight, endHi, endLo, endHeight, mapRoot, foldKeyHash, ids as pool-v2 §1's limbs.
// foldKeyHash is free here; the next fold and the reader bind it (§2 rule 1, §4.3 rule 2).`, keys)}// z_32, the empty map's root (§4.2).
global EMPTY_ROOT: Field = ${emptyRoot};

fn main(
${foldInputs}
    key: [Field; KEY_FIELDS], proof: [Field; PROOF_FIELDS], key_hash: Field, t0: T, m0: M, u0: U, t1: T, m1: M, u1: U,
) {
    let _ = fold_key_hash;
${foldPeriod}
    // The start: the header the public inputs name, the map empty.
    let (shi, slo) = id_limbs(m0.prev);
    assert(start_hi == shi, "start id");
    assert(start_lo == slo, "start id");
    assert(start_height == m0.height, "start height");
    assert(u0.root == EMPTY_ROOT, "empty map");
}
`;
}
/** The next fold: a period and the previous fold, which ends where it starts. */
export function foldNext(keys, firstFoldKeyHash) {
  return `${foldHeader(`// The next fold (succinct-read §4.3): it verifies a period's tree as the first fold does, and the previous fold
// under the first fold's key (a constant) or its own (foldKeyHash), with the same start and foldKeyHash, ending at
// this period's start header with this period's starting map root. Public inputs as the first fold's.`, keys)}global FIRST_FOLD_KEY_HASH: Field = ${firstFoldKeyHash};

fn main(
${foldInputs}
    key: [Field; KEY_FIELDS], proof: [Field; PROOF_FIELDS], key_hash: Field, t0: T, m0: M, u0: U, t1: T, m1: M, u1: U,
    previous_key: [Field; KEY_FIELDS], previous_proof: [Field; PROOF_FIELDS], previous_key_hash: Field,
) {
${foldPeriod}
    // The previous fold, ending at this period's start.
    assert((previous_key_hash == FIRST_FOLD_KEY_HASH) | (previous_key_hash == fold_key_hash), "previous fold key");
    let (shi, slo) = id_limbs(m0.prev);
    std::verify_proof_with_type(previous_key, previous_proof,
        [start_hi, start_lo, start_height, shi, slo, m0.height, u0.root, fold_key_hash], previous_key_hash, HONK_ZK);
}
`;
}
