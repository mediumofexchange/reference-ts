// Writes the exhaustion leaf circuit: node gen-leaf.mjs <CT> <CM> <E> [name]
// Three leaf kinds over one state. T: transaction bytes, one Blake2b compression and 128 scan steps a slot, and a list
// of the entries its scan emits (4 a slot at most); M: one compression a slot, for the transactions-root trees and the
// headers; U: one update of the subject map (a sparse Merkle tree) a slot, applying the T-leaves' entries in order.
import { mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { BUILD } from './compile.mjs';
import { MODES, BSEL, BYTEV, ACT, ACTIONS } from './machine.mjs';

export const S = 18, D = 32;
export const TAG = { TX: 1, ENTRY: 2, LEAF: 3, NODE: 4, STATE: 5, CHAL: 6 };
export const EL_PER_SLOT = 4;
// The byte table without the VLQ checks a leaf drops: cont + 2 cls.
export const BYTEV2 = BYTEV.map(v => (v & 1) + 2 * (v >> 3));
export const FIELDS2 = ['NEXT', 'RK', 'RC', 'RV', 'C1K', 'C1C', 'C1V', 'C2K', 'C2C', 'C2B', 'VK', 'OEND', 'HM', 'HB', 'LM', 'LB', 'SHM', 'SHC'];

const arr = (name, type, xs) => `global ${name}: [${type}; ${xs.length}] = [${xs.join(', ')}];\n`;
const fld = (x) => (x < 0 ? `-${-x}` : `${x}`);

export function source(CT, CM, E) {
  let s = `// Generated by gen-leaf.mjs: the exhaustion leaf (CT ${CT}, CM ${CM}, E ${E}).\nmod blake2b;\n`;
  s += `global CT: u32 = ${CT};\nglobal CM: u32 = ${CM};\nglobal E: u32 = ${E};\nglobal EL: u32 = ${EL_PER_SLOT * CT};\nglobal S: u32 = ${S};\nglobal D: u32 = ${D};\n`;
  s += Object.entries(TAG).map(([k, v]) => `global TAG_${k}: Field = ${v};\n`).join('');
  s += arr('BSEL', 'u32', BSEL) + arr('BYTEV', 'Field', BYTEV2) + arr('ACT', 'u32', ACT);
  for (const f of FIELDS2) s += arr(`A_${f}`, f === 'NEXT' ? 'u32' : 'Field', ACTIONS.map(a => fld(a[f])));
  s += `global P32: Field = 4294967296;\nglobal P64: Field = 18446744073709551616;\nglobal P128: Field = 340282366920938463463374607431768211456;\n`;
  s += String.raw`
pub struct T {
    h: [u64; 8], t: u64, in_tx: bool,
    mode: u32, rr: Field, c1: Field, c2: Field, a: Field, p: Field, hi: Field, lo: Field, sh: Field, outi: Field,
    height: Field, j: Field, chain: Field, echain: Field,
}
pub struct U { chain: Field, root: Field }
pub struct M {
    prev: [u64; 4], height: Field, mh: [u64; 8], hc: u64, in_hdr: bool, j: Field,
    stack: [[u64; 4]; S + 2], sp: u32, chain: Field,
}

fn perm3(a: Field, b: Field, c: Field, tag: Field) -> Field {
    std::hash::poseidon2_permutation([a, b, c, tag])[0]
}
fn pack3(w: [u64; 3]) -> Field { w[0] as Field + w[1] as Field * P64 + w[2] as Field * P128 }
// The state as field elements, hashed two at a time.
fn state_hash(t: T, m: M, u: U) -> Field {
    let mut f: [Field; 18 + 11 + 3 * (S + 2) + 1] = [0; 18 + 11 + 3 * (S + 2) + 1];
    f[0] = pack3([t.h[0], t.h[1], t.h[2]]); f[1] = pack3([t.h[3], t.h[4], t.h[5]]); f[2] = pack3([t.h[6], t.h[7], t.t]);
    f[3] = t.in_tx as Field; f[4] = t.mode as Field; f[5] = t.rr; f[6] = t.c1; f[7] = t.c2; f[8] = t.a; f[9] = t.p;
    f[10] = t.hi; f[11] = t.lo; f[12] = t.sh; f[13] = t.outi; f[14] = t.height; f[15] = t.j; f[16] = t.chain; f[17] = u.root;
    f[18] = pack3([m.prev[0], m.prev[1], m.prev[2]]); f[19] = pack3([m.prev[3], m.hc, 0]); f[20] = m.height;
    f[21] = pack3([m.mh[0], m.mh[1], m.mh[2]]); f[22] = pack3([m.mh[3], m.mh[4], m.mh[5]]); f[23] = pack3([m.mh[6], m.mh[7], 0]);
    f[24] = m.in_hdr as Field; f[25] = m.j; f[26] = m.sp as Field; f[27] = m.chain; f[28] = u.chain;
    for i in 0..S + 2 {
        let w = m.stack[i];
        f[29 + 3 * i] = pack3([w[0], w[1], w[2]]);
        f[30 + 3 * i] = w[3] as Field;
        f[31 + 3 * i] = 0;
    }
    f[89] = t.echain;
    let mut x: Field = 0;
    for i in 0..(f.len() / 2) { x = perm3(x, f[2 * i], f[2 * i + 1], TAG_STATE); }
    x
}

unconstrained fn inverse(x: Field) -> Field { if x == 0 { 0 } else { 1 / x } }
unconstrained fn split_bytev(v: Field) -> (bool, u8) { let w = v as u32; ((w & 1) == 1, (w >> 1) as u8) }
unconstrained fn as_index(v: Field) -> u32 { v as u32 }
unconstrained fn prefix(n: Field, i: u32) -> bool { (i as Field).lt(n) }
unconstrained fn split_lo(x: Field) -> (Field, [bool; 32]) {
    let v = x as u128;
    let k = (v % 4294967296) as u32;
    let mut bits = [false; 32];
    for i in 0..32 { bits[i] = ((k >> i) & 1) == 1; }
    ((v / 4294967296) as Field, bits)
}

// 1 if x is zero, else 0.
fn is_zero(x: Field) -> Field {
    // Safety: z is 1 - x inv with x z = 0, so z is 1 exactly when x is 0.
    let inv = unsafe { inverse(x) };
    let z = 1 - x * inv;
    assert(x * z == 0);
    z
}
fn index(x: Field) -> u32 {
    // Safety: the u32 is constrained equal to x.
    let i = unsafe { as_index(x) };
    assert(i as Field == x);
    i
}
// act[j] = (j < n) for n in [0, 128]: non-increasing bits summing to n.
fn mask(n: Field) -> [Field; 128] {
    let mut out = [0; 128];
    let mut sum: Field = 0;
    let mut was: Field = 1;
    for j in 0..128 {
        // Safety: the bits are constrained boolean, non-increasing, and to sum to n.
        let b = unsafe { prefix(n, j) } as Field;
        assert(b * (1 - was) == 0);
        was = b;
        sum += b;
        out[j] = b;
    }
    assert(sum == n);
    out
}
// The little-endian 64-bit word at byte offset o.
fn le_word(b: [u8; 128], o: u32) -> Field {
    let mut w: Field = 0;
    for i in 0..8 { w = w * 256 + b[o + 7 - i] as Field; }
    w
}
fn words(b: [u8; 128]) -> [u64; 16] {
    let mut m = [0; 16];
    for i in 0..16 { m[i] = blake2b::word(b, i); }
    m
}
// Where on is 1, the 32 bytes at offset o spell d.
fn spells(on: Field, b: [u8; 128], o: u32, d: [u64; 4]) {
    for k in 0..4 { assert(on * (le_word(b, o + 8 * k) - d[k] as Field) == 0); }
}
fn id_fields(d: [u64; 4]) -> (Field, Field) {
    (d[0] as Field + d[1] as Field * P64, d[2] as Field + d[3] as Field * P64)
}

fn main(
    sin: pub Field, sout: pub Field, key_node: pub Field, t0: T, m0: M, u0: U,
//<T>
    tb: [[u8; 128]; CT], tlen: [Field; CT], tstart: [bool; CT], tnew: [bool; CT], tlast: [bool; CT],
    lu: [bool; EL], lhi: [Field; EL], llo: [Field; EL], lpack: [Field; EL],
//</T>
//<U>
    uu: [bool; E], uhi: [Field; E], ulo: [Field; E], upack: [Field; E], ucnt: [Field; E], uchain: [Field; E],
    usib: [[Field; D]; E],
//</U>
//<M>
    mb: [[u8; 128]; CM], mlen: [Field; CM], mop: [[bool; 5]; CM], mlast: [bool; CM], mid: [[u64; 4]; CM],
//</M>
) {
    // key_node is the aggregation's node key, which a leaf only carries for its parent to compare.
    assert(key_node == key_node);
    assert(state_hash(t0, m0, u0) == sin);
    let mut t = t0;
    let mut m = m0;
    let mut u = u0;

//<T>
    let g = std::hash::poseidon2_permutation([sin, sout, 0, TAG_CHAL]);
    let (chal_gamma, chal_delta) = (g[0], g[1]);
    // The entry list: what the scan emits, in order of position, each joining the T-leaves' entry chain.
    let mut acc_list: Field = 1;
    let mut was_used = true;
    let mut last_pack: Field = 0;
    for k in 0..EL {
        let used = lu[k] as Field;
        assert(used * (1 - was_used as Field) == 0);
        was_used = lu[k];
        let (hi, lo, pk) = (lhi[k], llo[k], lpack[k]);
        hi.assert_max_bit_size::<128>();
        lo.assert_max_bit_size::<128>();
        pk.assert_max_bit_size::<96>();
        if k > 0 {
            (used * (pk - last_pack - 1)).assert_max_bit_size::<96>();
        }
        last_pack = pk;
        acc_list = acc_list * (1 + used * (chal_gamma - (hi + chal_delta * (lo + chal_delta * pk)) - 1));
        let next = perm3(t.echain, hi + pk * P128, lo, TAG_ENTRY);
        t.echain = t.echain + used * (next - t.echain);
    }

    // T slots.
    let mut tacc: Field = 1;
    for s in 0..CT {
        let len = tlen[s];
        let used = 1 - is_zero(len);
        let act = mask(len);
        let st = tstart[s] as Field;
        let la = tlast[s] as Field;
        let nw = tnew[s] as Field;
        assert(st * (1 - used) == 0);
        assert(la * (1 - used) == 0);
        assert(nw * (1 - st) == 0);
        assert(st * (t.in_tx as Field) == 0);
        assert((1 - st) * used * (1 - t.in_tx as Field) == 0);
        assert((1 - la) * used * (len - 128) == 0);
        let b = tb[s];
        for j in 0..128 { assert(b[j] as Field * (1 - act[j]) == 0); }
        let h_in = if tstart[s] { blake2b::iv0() } else { t.h };
        let tt = if tstart[s] { 0 } else { t.t };
        let t_new = tt + (index(len) as u64);
        let d = blake2b::compress(h_in, words(b), t_new, tlast[s]);
        if used == 1 {
            t.h = d;
            t.t = t_new;
            t.in_tx = !tlast[s];
        }
        // A transaction starts: its labels advance and the machine restarts.
        t.height = t.height + nw;
        t.j = t.j + st - nw * (t.j + 1);
        if tstart[s] {
            t.mode = 0;
            t.a = 0;
            t.p = 1;
            t.outi = 0;
        }
        let hj = t.height * P32 + t.j;
        // The scan.
        let mut mode = t.mode;
        let (mut rr, mut c1, mut c2, mut a, mut p, mut hi, mut lo, mut sh, mut outi) = (t.rr, t.c1, t.c2, t.a, t.p, t.hi, t.lo, t.sh, t.outi);
        for j in 0..128 {
            let byte = b[j];
            let bf = byte as Field;
            let v = BYTEV[BSEL[mode] * 256 + (byte as u32)];
            // Safety: v = cont + 2 cls with cont a bit and cls a u8 has one solution.
            let (cont, cls) = unsafe { split_bytev(v) };
            assert(v == (cont as Field) + 2 * (cls as Field));
            let low = bf - 128 * (cont as Field);
            let vv = a + low * p;
            let z_r = is_zero(rr - 1);
            let z_v = is_zero(vv);
            let z_32 = is_zero(vv - 32);
            let z_c1 = is_zero(c1 - 1);
            let z_c2 = is_zero(c2 - 1);
            let key = index((mode as Field) * 128 + (cls as Field) * 32 + z_r * 16 + z_v * 8 + z_32 * 4 + z_c1 * 2 + z_c2);
            let id = ACT[key];
            rr = A_RK[id] * rr + A_RC[id] + A_RV[id] * vv;
            c1 = A_C1K[id] * c1 + A_C1C[id] + A_C1V[id] * vv;
            c2 = A_C2K[id] * c2 + A_C2C[id] + A_C2B[id] * bf;
            let vk = A_VK[id];
            a = vk * vv;
            p = vk * (128 * p - 1) + 1;
            hi = A_HM[id] * hi + A_HB[id] * bf;
            lo = A_LM[id] * lo + A_LB[id] * bf;
            sh = A_SHM[id] * sh + A_SHC[id];
            // An output with the shape ends here: its entry joins the multiset.
            let oend = A_OEND[id] * act[j];
            let emit = oend * sh * (sh - 1) / 2;
            let entry = hi + chal_delta * (lo + chal_delta * (hj * P32 + outi));
            tacc = tacc + emit * tacc * (chal_gamma - entry - 1);
            outi = outi + oend;
            mode = A_NEXT[id];
        }
        if used == 1 {
            t.mode = mode;
            t.rr = rr; t.c1 = c1; t.c2 = c2; t.a = a; t.p = p; t.hi = hi; t.lo = lo; t.sh = sh; t.outi = outi;
        }
        // A transaction ends: its id joins the chain with its labels.
        let (idlo, idhi) = id_fields([d[0], d[1], d[2], d[3]]);
        let next = perm3(t.chain, idhi, idlo + hj * P128, TAG_TX);
        t.chain = t.chain + la * (next - t.chain);
    }

//</T>
//<M>
    // M slots.
    for s in 0..CM {
        let o = mop[s];
        let (o_id, o_wid, o_mrg, o_lift, o_hdr) = (o[0] as Field, o[1] as Field, o[2] as Field, o[3] as Field, o[4] as Field);
        let any = o_id + o_wid + o_mrg + o_lift + o_hdr;
        assert(any * (1 - any) == 0);
        let tree = any - o_hdr;
        let ml = mlast[s] as Field;
        assert(ml * (1 - o_hdr) == 0);
        let len = mlen[s];
        let act = mask(len);
        assert(o_id * (len - 33) == 0);
        assert(o_wid * (len - 32) == 0);
        assert(o_mrg * (len - 65) == 0);
        assert(o_lift * (len - 33) == 0);
        assert(o_hdr * (1 - ml) * (len - 128) == 0);
        assert(o_hdr * is_zero(len) == 0);
        let b = mb[s];
        for j in 0..128 { assert(any * (b[j] as Field) * (1 - act[j]) == 0); }
        assert((o_id + o_wid) * (b[0] as Field) == 0);
        assert((o_mrg + o_lift) * (b[0] as Field - 1) == 0);
        assert(tree * (m.in_hdr as Field) == 0);
        let sp = m.sp;
        let top = m.stack[sp + 1];
        let below = m.stack[sp];
        let first = o_hdr * (1 - m.in_hdr as Field);
        spells(o_id, b, 1, mid[s]);
        spells(o_mrg, b, 1, below);
        spells(o_mrg, b, 33, top);
        spells(o_lift, b, 1, top);
        spells(first, b, 1, m.prev);
        spells(first, b, 65, top);
        assert(first * (sp as Field - 1) == 0);
        // Positions 0 and 1 are sentinels: a merge needs two live entries and a lift one, so no push is ever lost
        // below the stack and the root depends on every id pushed.
        assert(o_mrg * is_zero(sp as Field - 1) == 0);
        assert(o_lift * is_zero(sp as Field) == 0);
        let chain_hdr = (o_hdr == 1) & m.in_hdr;
        let h_in = if chain_hdr { m.mh } else { blake2b::iv0() };
        let tt = if chain_hdr { m.hc } else { 0 };
        let t_new = tt + (index(len) as u64);
        let last = (o_hdr == 0) | mlast[s];
        let d = blake2b::compress(h_in, words(b), t_new, last);
        // The stack.
        let push = o_id + o_wid;
        let widx = index(sp as Field + 1 + push - o_mrg);
        let write = push + o_mrg + o_lift;
        let old = m.stack[widx];
        let mut nv = old;
        for k in 0..4 { nv[k] = if write == 1 { d[k] } else { old[k] }; }
        m.stack[widx] = nv;
        let (idlo, idhi) = id_fields(mid[s]);
        let next = perm3(m.chain, idhi, idlo + ((m.height + 1) * P32 + m.j) * P128, TAG_TX);
        m.chain = m.chain + o_id * (next - m.chain);
        m.j = m.j + o_id;
        // The header.
        if o_hdr == 1 {
            m.mh = d;
            m.hc = t_new;
            m.in_hdr = !mlast[s];
        }
        let done = o_hdr * ml;
        if done == 1 {
            m.prev = [d[0], d[1], d[2], d[3]];
        }
        m.height = m.height + done;
        m.j = m.j * (1 - done);
        m.sp = index((sp as Field + push - o_mrg) * (1 - done));
    }
//</M>
//<U>
    // The subject map: each used slot takes the next entry of the chain and appends it to its key's chain.
    let mut was_used = true;
    for k in 0..E {
        let used = uu[k] as Field;
        assert(used * (1 - was_used as Field) == 0);
        was_used = uu[k];
        let (hi, lo, pk) = (uhi[k], ulo[k], upack[k]);
        let next = perm3(u.chain, hi + pk * P128, lo, TAG_ENTRY);
        u.chain = u.chain + used * (next - u.chain);
        // Safety: q and the key bits recompose lo, with q below 2^96.
        let (q, bits) = unsafe { split_lo(lo) };
        q.assert_max_bit_size::<96>();
        let mut key: Field = 0;
        for i in 0..32 { key = key * 2 + bits[31 - i] as Field; }
        assert(q * P32 + key == lo);
        let (cnt, chain) = (ucnt[k], uchain[k]);
        assert(is_zero(cnt) * chain == 0);
        let old_leaf = (1 - is_zero(cnt)) * perm3(cnt, chain, 0, TAG_LEAF);
        let new_chain = perm3(chain, hi + pk * P128, lo, TAG_ENTRY);
        let new_leaf = perm3(cnt + 1, new_chain, 0, TAG_LEAF);
        let mut a = old_leaf;
        let mut b = new_leaf;
        for i in 0..D {
            let sib = usib[k][i];
            let (al, ar) = if bits[i] { (sib, a) } else { (a, sib) };
            let (bl, br) = if bits[i] { (sib, b) } else { (b, sib) };
            a = perm3(al, ar, 0, TAG_NODE);
            b = perm3(bl, br, 0, TAG_NODE);
        }
        assert(used * (a - u.root) == 0);
        u.root = u.root + used * (b - u.root);
    }
//</U>
    assert(state_hash(t, m, u) == sout);
//<T>
    assert(tacc == acc_list);
//</T>
}
`;
  const keep = { T: CT > 0, M: CM > 0, U: E > 0 };
  s = s.replace(/^\/\/<(T|M|U)>\n([\s\S]*?)^\/\/<\/\1>\n/gm, (m0, k, body) => (keep[k] ? body : ''));
  if (!keep.T) s = s.replace(/^\s*let mut t = t0;/m, '    let t = t0;');
  if (!keep.M) s = s.replace(/^\s*let mut m = m0;/m, '    let m = m0;');
  if (!keep.U) s = s.replace(/^\s*let mut u = u0;/m, '    let u = u0;');
  return s;
}

export function project(CT, CM, E, name = `leaf_${CT}_${CM}_${E}`) {
  const dir = path.join(BUILD, name);
  mkdirSync(path.join(dir, 'src'), { recursive: true });
  writeFileSync(path.join(dir, 'Nargo.toml'), `[package]\nname = "${name}"\ntype = "bin"\nauthors = []\n[dependencies]\n`);
  copyFileSync(path.join(import.meta.dirname, 'blake2b.nr'), path.join(dir, 'src/blake2b.nr'));
  writeFileSync(path.join(dir, 'src/main.nr'), source(CT, CM, E));
  return dir;
}
